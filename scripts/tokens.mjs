// Generates CSS custom properties + the Tailwind v4 @theme mapping from
// replica/design/tokens.json. Run after any token change: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const t = JSON.parse(readFileSync(new URL("replica/design/tokens.json", root), "utf8"));

const vars = [];
const theme = [];
for (const [k, v] of Object.entries(t.color)) {
  vars.push(`  --c-${k}: ${v};`);
  theme.push(`  --color-${k}: var(--c-${k});`);
}
for (const [k, v] of Object.entries(t.radius)) theme.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.type)) {
  theme.push(`  --text-${k}: ${v.size / 16}rem;`);
  theme.push(`  --text-${k}--line-height: ${v.line / 16}rem;`);
  theme.push(`  --text-${k}--font-weight: ${v.weight};`);
}
for (const [k, v] of Object.entries(t.shadow)) theme.push(`  --shadow-${k}: ${v};`);
theme.push(`  --font-sans: var(--font-geist-sans), ${t.font.sans};`);
theme.push(`  --font-mono: var(--font-geist-mono), ${t.font.mono};`);
theme.push(`  --ease-brand: ${t.motion.ease};`);

const css = `/* Generated by scripts/tokens.mjs from replica/design/tokens.json. Do not edit. */
:root {
${vars.join("\n")}
  --motion-fast: ${t.motion.fast};
  --motion-base: ${t.motion.base};
  --header-h: ${t.layout.header}px;
  --sidebar-w: ${t.layout.sidebar}px;
  color-scheme: dark;
}

@theme inline {
${theme.join("\n")}
}
`;

writeFileSync(new URL("web/src/app/tokens.css", root), css);
writeFileSync(new URL("replica/design/tokens.css", root), css);
console.log("tokens.css written");
